import {build} from 'esbuild';
import {readdir, readFile, writeFile} from 'node:fs/promises';
import {join} from 'node:path';
await build({entryPoints:['note-editor.js'], bundle:true, minify:true, format:'iife',
  outfile:'../web/note-editor.js', target:['es2022'], legalComments:'eof'});
// Preserve dependency licenses alongside the reproducible source and lockfile.
const packages=[];
for(const name of await readdir('node_modules')) {
  if(name.startsWith('.'))continue;
  if(name.startsWith('@')) for(const child of await readdir(join('node_modules',name)))packages.push(join(name,child));
  else packages.push(name);
}
const notices=['# Rich-text editor third-party licenses\n\nGenerated by editor/build.mjs.'];
for(const name of packages.sort()) {
  const directory=join('node_modules',name);
  const licenses=(await readdir(directory)).filter(file=>/^licen[sc]e(?:\.|$)/i.test(file));
  for(const file of licenses)notices.push(`\n## ${name}\n\n${await readFile(join(directory,file),'utf8')}`);
}
await writeFile('THIRD_PARTY_LICENSES.md',notices.join('\n'));
